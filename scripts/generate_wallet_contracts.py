def write_json(path: Path, value) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n")


def generate_schemas() -> None:
    definitions = {}
    for name, model in {**vars(models), **vars(wallet_inputs)}.items():
        if (
            isinstance(model, type)
            and issubclass(model, models.ContractModel)
            and name != "ContractModel"
        ):
            schema = model.model_json_schema(by_alias=True)
            definitions.update(schema.pop("$defs", {}))
            definitions[name] = schema
    write_json(
        GENERATED / "json/wallet-contract.schema.json",
        {
            "$schema": "https://json-schema.org/draft/2020-12/schema",
            "title": "OriginProof wallet shared contract",
            "x-revision": models.REVISION,
            "x-implementation-status": "PREPARATION_REVIEW_REQUIRED",
            "$defs": definitions,
        },
    )
    lines = [
        "// Generated by scripts/generate_wallet_contracts.py; do not edit.",
        f"// {models.REVISION}; endpoint availability is described by the runtime OpenAPI.",
        "",
    ]
    for name, schema in sorted(definitions.items()):
        lines.extend((typescript_interface(name, schema), ""))
    types = {
        name: [{"name": key, "type": kind} for key, kind in fields]
        for name, fields in EIP712_TYPES.items()
    }
    lines.append("export const WALLET_EIP712_TYPES = " + json.dumps(types, indent=2) + " as const;")
    lines.append("export const WALLET_SIGNATURE_SCHEMA = " + json.dumps(SIGNATURE_SCHEMA) + ";")
    output = GENERATED / "types/wallet-contract.ts"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines))

    # OpenAPI is generated from the same models, but is intentionally not mounted on FastAPI.
    components = json.loads(json.dumps(definitions).replace("#/$defs/", "#/components/schemas/"))
    paths = {}
    for method, path, request, response, status, audience in OPERATIONS:
        operation = {
            "operationId": method
            + "_"
            + path.strip("/").replace("/", "_").replace("{", "").replace("}", ""),
            "x-audience": audience,
            "x-implementation-status": "PLANNED",
            "security": [] if audience == "public" else [{"sessionCookie": []}],
            "responses": {str(status): {"description": "Expected success"}},
        }
        if response == "binary":
            operation["responses"][str(status)]["content"] = {
                "application/octet-stream": {"schema": {"type": "string", "format": "binary"}}
            }
        elif response:
            operation["responses"][str(status)]["content"] = {
                "application/json": {"schema": {"$ref": f"#/components/schemas/{response}"}}
            }
        if path == "/v3/verifications":
            operation["security"] = [{}, {"sessionCookie": []}]
        for code in (401, 403, 404, 409, 410, 422, 429, 503):
            operation["responses"][str(code)] = {
                "description": "Contract error; see the shared specification",
                "content": {
                    "application/json": {"schema": {"$ref": "#/components/schemas/ErrorResponse"}}
                },
            }
        parameters = []
        for part in path.split("/"):
            if part.startswith("{"):
                parameters.append(
                    {
                        "in": "path",
                        "name": part[1:-1],
                        "required": True,
                        "schema": {"type": "string"},
                    }
                )
        if method not in ("get",) and audience != "public":
            parameters.append(
                {
                    "in": "header",
                    "name": "X-CSRF-Token",
                    "required": True,
                    "schema": {"type": "string"},
                }
            )
        if path == "/v3/documents/{document_id}":
            parameters.append(
                {
                    "in": "query",
                    "name": "version",
                    "required": False,
                    "schema": {"type": "integer", "minimum": 1, "maximum": models.SAFE_INTEGER},
                }
            )
        operation["parameters"] = parameters
        if request:
            operation["requestBody"] = {
                "required": True,
                "content": {
                    "application/json": {"schema": {"$ref": f"#/components/schemas/{request}"}}
                },
            }
        paths.setdefault(path, {})[method] = operation
    write_json(
        GENERATED / "openapi/wallet-contract.openapi.json",
        {
            "openapi": "3.1.0",
            "info": {
                "title": "OriginProof wallet preparation API",
                "version": models.REVISION,
                "description": "Review contract only; routes are not implemented by this file.",
            },
            "paths": paths,
            "components": {
                "schemas": components,
                "securitySchemes": {
                    "sessionCookie": {
                        "type": "apiKey",
                        "in": "cookie",
                        "name": "originproof_session",
                    }
                },
            },
        },
    )


def make_golden() -> dict:
    domain = models.WalletDomain(chainId="31337", verifyingContract="0x" + "12" * 20)
    issuer = identifier_hash("iss_synthetic_public_office")
    key_id = identifier_hash("key_synthetic_public_office_001")
    doc_key = identifier_hash("doc_synthetic_notice_001")
    # Public synthetic test key 1, never a service/issuer key and never funded.
    test_key = keys.PrivateKey((1).to_bytes(32, "big"))
    signer = test_key.public_key.to_address()
    payments = models.PaymentContent(
        notice_type="PAYMENT_REQUEST",
        amount_minor=154000,
        currency="KRW",
        payee_bank_name="합성 시연 은행",
        payee_account_number="001234567890",
        payee_account_holder="합성 공공기관",
        payment_purpose="합성 행사 참가비",
        due_at=1792454400,
        official_url="https://example.invalid/notice/001",
    )
    official = models.OfficialContent(
        notice_type="OFFICIAL_DOCUMENT",
        institution_code="SYNTHETIC-001",
        document_type="PUBLIC_NOTICE",
        document_number="SYN-2026-001",
        title="합성 행사 안내",
        summary="실제 기관이나 납부 의무와 무관한 시연 자료입니다.",
        official_url="https://example.invalid/notice/001",
    )
    vectors = []
    for content in (payments, official):
        message = models.PublishMessage(
            issuerId=issuer,
            docKey=doc_key,
            documentId=document_id(issuer, doc_key),
            version=1,
            keyId=key_id,
            originalHash="0x" + "00" * 32,
            protectedHash="0x" + hashlib.sha256(canonical_json_bytes(content)).hexdigest(),
            contentSchema=CONTENT_SCHEMAS[content.notice_type],
            signatureSchema=SIGNATURE_SCHEMA,
            issuedAt=1791936000,
            expiresAt=1792540800,
            nonce="0",
            deadline=1791936300,
        )
        raw = original_bytes(message, content)
        message = message.model_copy(
            update={"original_hash": "0x" + hashlib.sha256(raw).hexdigest()}
        )
        validate_content(message, content)
        vectors.append((content.notice_type, message, content, raw))
    vectors.extend(
        [
            (
                "REVOKE",
                models.RevokeMessage(
                    issuerId=issuer,
                    docKey=doc_key,
                    documentId=document_id(issuer, doc_key),
                    version=1,
                    keyId=key_id,
                    nonce="1",
                    deadline=1791936600,
                ),
                None,
                None,
            ),
            (
                "KEY_PROOF",
                models.KeyProofMessage(
                    applicationId=identifier_hash("app_synthetic_001"),
                    issuerId=issuer,
                    signer=signer,
                    challengeNonce=identifier_hash("challenge_synthetic_001"),
                    deadline=1791936300,
                ),
                None,
                None,
            ),
        ]
    )
    output = {
        "revision": models.REVISION,
        "synthetic": True,
        "private_key": "NOT_INCLUDED",
        "runtime_status": "SIGNING_ONLY_NO_REGISTRY_IMPLEMENTATION",
        "vectors": [],
    }
    proposal = models.GovernanceProposal(
        action=1,
        issuerId=issuer,
        keyId=key_id,
        signer=signer,
        metadataHash=identifier_hash("synthetic public metadata"),
        nonce="0",
        deadline=1791936300,
    )
    output["governance"] = {
        "domain": domain.model_dump(by_alias=True),
        "proposal": proposal.model_dump(by_alias=True),
        "proposal_id": proposal_id(domain, proposal),
    }
    for label, message, content, raw in vectors:
        digest = wallet_digest(domain, message)
        signed = test_key.sign_msg_hash(bytes.fromhex(digest[2:])).to_bytes()
        signature = "0x" + (signed[:64] + bytes([signed[64] + 27])).hex()
        data = typed_data(domain, message)
        output["vectors"].append(
            {
                "label": label,
                "typed_data": data,
                "digest": digest,
                "signature": signature,
                "expected_signer": signer,
                "domain_separator": "0x" + struct_hash("EIP712Domain", data["domain"]).hex(),
                "struct_hash": "0x" + struct_hash(data["primaryType"], data["message"]).hex(),
                "protected_content": content.model_dump() if content else None,
                "protected_canonical_utf8": canonical_json_bytes(content).decode()
                if content
                else None,
                "original_base64": base64.b64encode(raw).decode() if raw else None,
                "original_utf8": raw.decode() if raw else None,
            }
        )
    return output


def generate_solidity_golden(golden: dict) -> None:
    lines = [
        "// SPDX-License-Identifier: MIT",
        "pragma solidity 0.8.26;",
        "// Generated by scripts/generate_wallet_contracts.py; synthetic signing test data only.",
        "import {IOriginProofWalletRegistry as Registry} "
        'from "../../src/IOriginProofWalletRegistry.sol";',
        "",
        "library WalletGolden {",
    ]
    for vector in golden["vectors"]:
        primary = vector["typed_data"]["primaryType"]
        suffix = vector["label"].lower()
        lines.append(
            f"    function {suffix}() internal pure returns (Registry.{primary} memory m) {{"
        )
        for name, kind in EIP712_TYPES[primary]:
            value = vector["typed_data"]["message"][name]
            literal = f'address(bytes20(hex"{value[2:]}"))' if kind == "address" else str(value)
            lines.append(f"        m.{name} = {literal};")
        lines.extend(
            (
                "    }",
                f"    bytes32 internal constant {vector['label']}_DIGEST =",
                f"        {vector['digest']};",
                f"    bytes internal constant {vector['label']}_SIGNATURE =",
                f'        hex"{vector["signature"][2:]}";',
                "",
            )
        )
    lines.append(
        "    function proposal() internal pure returns (Registry.GovernanceProposal memory p) {"
    )
    for name, value in golden["governance"]["proposal"].items():
        literal = f'address(bytes20(hex"{value[2:]}"))' if name == "signer" else str(value)
        lines.append(f"        p.{name} = {literal};")
    lines.extend(
        (
            "    }",
            "    bytes32 internal constant PROPOSAL_ID =",
            "        " + golden["governance"]["proposal_id"] + ";",
            "}",
            "",
        )
    )
    path = ROOT / "packages/contracts/test/generated/WalletGolden.sol"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines))


