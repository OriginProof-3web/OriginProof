def main() -> None:
    generate_schemas()
    golden = make_golden()
    write_json(GOLDEN, golden)
    generate_solidity_golden(golden)
    generate_examples(golden)
    compiled = (
        ROOT
        / "packages/contracts/out/IOriginProofWalletRegistry.sol/IOriginProofWalletRegistry.json"
    )
    if compiled.exists():
        write_json(
            ROOT / "packages/contracts/abi/IOriginProofWalletRegistry.json",
            json.loads(compiled.read_text())["abi"],
        )
    print(
        f"Generated {models.REVISION}: JSON Schema, TypeScript, planned OpenAPI, 4 signing vectors."
    )


if __name__ == "__main__":
    main()
