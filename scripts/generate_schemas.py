from __future__ import annotations

import json
from pathlib import Path

from originproof_core import (
    CardPaymentNotice,
    CardPaymentNoticeCandidate,
    SignedProofEnvelope,
    VerificationRequest,
    VerificationResult,
)

ROOT = Path(__file__).resolve().parents[1]
OUTPUT_DIR = ROOT / "packages" / "schemas" / "generated" / "json"
TYPES_OUTPUT = ROOT / "packages" / "schemas" / "generated" / "types" / "originproof.ts"
SCHEMAS = {
    "card-payment-notice.schema.json": CardPaymentNotice,
    "card-payment-notice-candidate.schema.json": CardPaymentNoticeCandidate,
    "signed-proof-envelope.schema.json": SignedProofEnvelope,
    "verification-request.schema.json": VerificationRequest,
    "verification-result.schema.json": VerificationResult,
}


def typescript_type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in schema:
        return " | ".join(typescript_type(item) for item in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])

    primitive = schema.get("type")
    if primitive == "string":
        return "string"
    if primitive in {"integer", "number"}:
        return "number"
    if primitive == "boolean":
        return "boolean"
    if primitive == "null":
        return "null"
    if primitive == "array":
        return f"{typescript_type(schema.get('items', {}))}[]"
    if primitive == "object":
        if "additionalProperties" in schema and isinstance(schema["additionalProperties"], dict):
            return f"Record<string, {typescript_type(schema['additionalProperties'])}>"
        return "Record<string, unknown>"
    return "unknown"


def typescript_interface(name: str, schema: dict) -> str:
    required = set(schema.get("required", []))
    fields = []
    for field, field_schema in schema.get("properties", {}).items():
        optional = "" if field in required else "?"
        fields.append(f"  {field}{optional}: {typescript_type(field_schema)};")
    return "\n".join([f"export interface {name} {{", *fields, "}"])


def write_types(schemas: dict[str, dict]) -> None:
    definitions: dict[str, dict] = {}
    for schema in schemas.values():
        definitions.update(schema.get("$defs", {}))

    lines = [
        "// Generated by scripts/generate_schemas.py. Do not edit manually.",
        "// Source: packages/python/originproof_core/models.py",
        "",
    ]
    emitted = set()
    for name, definition in definitions.items():
        if "enum" in definition:
            lines.append(f"export type {name} = {typescript_type(definition)};")
        else:
            lines.append(typescript_interface(name, definition))
        lines.append("")
        emitted.add(name)

    for schema in schemas.values():
        if schema["title"] in emitted:
            continue
        lines.append(typescript_interface(schema["title"], schema))
        lines.append("")

    TYPES_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    TYPES_OUTPUT.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    generated = {}
    for filename, model in SCHEMAS.items():
        schema = model.model_json_schema()
        schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
        (OUTPUT_DIR / filename).write_text(
            json.dumps(schema, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
        )
        generated[filename] = schema
    write_types(generated)
    print(f"Generated {len(SCHEMAS)} JSON Schemas and TypeScript types")


if __name__ == "__main__":
    main()
